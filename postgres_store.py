"""Persistent order and loyalty operations. Monetary amounts are integer kopecks."""
import secrets
import psycopg
from psycopg.rows import dict_row
from datetime import datetime, timezone

STATUSES = {'new', 'quoted', 'in_progress', 'completed', 'cancelled'}
TRANSITIONS = {'new': {'quoted', 'cancelled'}, 'quoted': {'in_progress', 'cancelled'}, 'in_progress': {'completed', 'cancelled'}, 'completed': set(), 'cancelled': set()}

def now():
    return datetime.now(timezone.utc).isoformat()

class PostgresStore:
    def __init__(self, database_url):
        self.database_url = database_url
        with self.connect() as db:
            db.execute("SELECT pg_advisory_xact_lock(841326001)")
            db.execute("CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY)")
            db.execute("CREATE TABLE IF NOT EXISTS users (id BIGINT PRIMARY KEY, name TEXT NOT NULL, ref_code TEXT NOT NULL UNIQUE, referred_by BIGINT REFERENCES users(id), created_at TEXT NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS orders (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), kind TEXT NOT NULL, topic TEXT NOT NULL, deadline TEXT NOT NULL, details TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'new', price_kopecks BIGINT, paid_kopecks BIGINT, redeemed_kopecks BIGINT NOT NULL DEFAULT 0, created_at TEXT NOT NULL)")
            db.execute("CREATE TABLE IF NOT EXISTS points (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id), order_id BIGINT NOT NULL REFERENCES orders(id), amount_kopecks BIGINT NOT NULL CHECK(amount_kopecks != 0), reason TEXT NOT NULL, created_at TEXT NOT NULL, UNIQUE(order_id, reason))")
            db.execute("INSERT INTO schema_migrations(version) VALUES (1) ON CONFLICT DO NOTHING")

    def connect(self):
        return psycopg.connect(self.database_url, row_factory=dict_row, connect_timeout=10)

    def register_user(self, user_id, name, referral_code=None):
        if not isinstance(user_id, int) or user_id <= 0 or not name.strip():
            raise ValueError('Invalid user')
        with self.connect() as db:
            db.execute('SELECT pg_advisory_xact_lock(841326002)')
            existing = db.execute('SELECT * FROM users WHERE id=%s', (user_id,)).fetchone()
            if existing:
                db.execute('UPDATE users SET name=%s WHERE id=%s', (name.strip(), user_id))
            else:
                referrer = db.execute('SELECT id FROM users WHERE ref_code=%s', (referral_code,)).fetchone() if referral_code else None
                db.execute('INSERT INTO users VALUES (%s, %s, %s, %s, %s)', (user_id, name.strip(), secrets.token_urlsafe(12), referrer['id'] if referrer and referrer['id'] != user_id else None, now()))
            return dict(db.execute('SELECT * FROM users WHERE id=%s', (user_id,)).fetchone())

    def create_order(self, user_id, kind, topic, deadline, details=''):
        if any(not isinstance(v, str) or not v.strip() for v in (kind, topic, deadline)) or not isinstance(details, str):
            raise ValueError('Required fields missing')
        try:
            datetime.strptime(deadline, '%Y-%m-%d')
        except ValueError:
            raise ValueError('Invalid deadline') from None
        if max(map(len, (kind, topic, deadline, details))) > 4000:
            raise ValueError('Field too long')
        with self.connect() as db:
            cursor = db.execute('INSERT INTO orders (user_id,kind,topic,deadline,details,created_at) VALUES (%s,%s,%s,%s,%s,%s) RETURNING id', (user_id,kind.strip(),topic.strip(),deadline,details.strip(),now()))
            return cursor.fetchone()['id']

    def list_orders(self, user_id):
        with self.connect() as db:
            return [dict(row) for row in db.execute('SELECT * FROM orders WHERE user_id=%s ORDER BY id DESC', (user_id,))]

    def quote(self, order_id, price_kopecks):
        if type(price_kopecks) is not int or price_kopecks <= 0:
            raise ValueError('Price must be positive integer kopecks')
        with self.connect() as db:
            db.execute('SELECT pg_advisory_xact_lock(841326002)')
            result = db.execute("UPDATE orders SET price_kopecks=%s, status='quoted' WHERE id=%s AND status IN ('new','quoted') AND redeemed_kopecks=0", (price_kopecks, order_id))
            if result.rowcount != 1:
                raise ValueError('Order not found or cannot be quoted')

    def change_status(self, order_id, status):
        if status not in STATUSES or status in ('quoted', 'in_progress'):
            raise ValueError('Use quote or payment confirmation')
        with self.connect() as db:
            db.execute('SELECT pg_advisory_xact_lock(841326002)')
            row = db.execute('SELECT status FROM orders WHERE id=%s', (order_id,)).fetchone()
            if not row or status not in TRANSITIONS[row['status']]:
                raise ValueError('Invalid status transition')
            if status == 'cancelled':
                redeemed = db.execute('SELECT user_id, redeemed_kopecks FROM orders WHERE id=%s', (order_id,)).fetchone()
                if redeemed['redeemed_kopecks']:
                    db.execute('INSERT INTO points (user_id,order_id,amount_kopecks,reason,created_at) VALUES (%s,%s,%s,%s,%s)', (redeemed['user_id'], order_id, redeemed['redeemed_kopecks'], 'redemption_refund', now()))
            db.execute('UPDATE orders SET status=%s WHERE id=%s', (status, order_id))

    def redeem(self, user_id, order_id, amount_kopecks):
        if type(amount_kopecks) is not int or amount_kopecks <= 0:
            raise ValueError('Invalid amount')
        with self.connect() as db:
            db.execute('SELECT pg_advisory_xact_lock(841326002)')
            order = db.execute('SELECT * FROM orders WHERE id=%s AND user_id=%s', (order_id, user_id)).fetchone()
            balance = db.execute('SELECT COALESCE(SUM(amount_kopecks),0) AS total FROM points WHERE user_id=%s', (user_id,)).fetchone()['total']
            if not order or order['status'] != 'quoted' or order['redeemed_kopecks'] or amount_kopecks > order['price_kopecks'] // 2 or amount_kopecks > balance:
                raise ValueError('Cannot redeem this amount')
            db.execute('INSERT INTO points (user_id,order_id,amount_kopecks,reason,created_at) VALUES (%s,%s,%s,%s,%s)', (user_id, order_id, -amount_kopecks, 'redemption', now()))
            db.execute('UPDATE orders SET redeemed_kopecks=%s WHERE id=%s', (amount_kopecks, order_id))

    def confirm_payment(self, order_id, paid_kopecks):
        if type(paid_kopecks) is not int or paid_kopecks <= 0:
            raise ValueError('Invalid paid amount')
        with self.connect() as db:
            db.execute('SELECT pg_advisory_xact_lock(841326002)')
            order = db.execute('SELECT o.*, u.referred_by FROM orders o JOIN users u ON u.id=o.user_id WHERE o.id=%s', (order_id,)).fetchone()
            if not order or order['status'] != 'quoted' or order['price_kopecks'] - order['redeemed_kopecks'] != paid_kopecks:
                raise ValueError('Order is not awaiting this payment')
            db.execute("UPDATE orders SET status='in_progress', paid_kopecks=%s WHERE id=%s", (paid_kopecks, order_id))
            if order['referred_by']:
                reward = paid_kopecks // 10
                if reward:
                    db.execute('INSERT INTO points (user_id,order_id,amount_kopecks,reason,created_at) VALUES (%s,%s,%s,%s,%s)', (order['referred_by'], order_id, reward, 'referral_payment', now()))

    def profile(self, user_id):
        with self.connect() as db:
            user = db.execute('SELECT id,name,ref_code FROM users WHERE id=%s', (user_id,)).fetchone()
            if not user:
                raise ValueError('User not found')
            balance = db.execute('SELECT COALESCE(SUM(amount_kopecks),0) AS total FROM points WHERE user_id=%s', (user_id,)).fetchone()['total']
            invited = db.execute('SELECT COUNT(*) AS total FROM users WHERE referred_by=%s', (user_id,)).fetchone()['total']
            return {**dict(user), 'balance_kopecks': balance, 'invited': invited}
